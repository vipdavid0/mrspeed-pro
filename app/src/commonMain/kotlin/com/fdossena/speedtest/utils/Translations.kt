package com.fdossena.speedtest.utils

object Translations {
    fun get(rawId: String, language: String, vararg args: Any): String {
        val id = extractResourceKey(rawId)
        val lang = language.lowercase().replace("_", "-")
        val code = if (lang.contains("-")) lang else lang.take(2)
        val targetCode = when (code) {
            "zh-tw", "zh-hk", "zh-hant" -> "zh-tw"
            "zh", "zh-cn", "zh-hans" -> "zh"
            "hr", "bs", "sr", "bg", "be", "mk", "uk", "pl", "cs", "sk", "sl" -> if (translationsMap.containsKey(code)) code else "ru"
            "ca", "gl", "eu", "ro" -> if (translationsMap.containsKey(code)) code else "es"
            "ms", "jv", "su", "id", "fil" -> if (translationsMap.containsKey(code)) code else "es"
            "mr", "ne", "gu", "kn", "pa", "ta", "te", "ml", "bn", "si" -> if (translationsMap.containsKey(code)) code else "hi"
            "ps", "ur", "he" -> if (translationsMap.containsKey(code)) code else "ar"
            "nl", "sv", "no", "da", "af", "is", "fi" -> if (translationsMap.containsKey(code)) code else "de"
            else -> code
        }

        val langMap = translationsMap[targetCode] ?: translationsMap[code] ?: return Strings.get(id, *args)
        val template = langMap[id] ?: return Strings.get(id, *args)
        var str = template
        args.forEachIndexed { i, arg ->
            str = str.replace("%${i + 1}\$s", arg.toString()).replace("%s", arg.toString())
        }
        return str
    }

