    fun getForLang(id: String, language: String, vararg args: Any): String {
        val langMap = when (language.lowercase().take(2)) {
            "ar" -> arMap
            "es" -> esMap
            else -> map
        }
        var str = langMap[id] ?: map[id] ?: id
        args.forEachIndexed { i, arg ->
            str = str.replace("%${i + 1}\$s", arg.toString()).replace("%s", arg.toString())
        }
        return str
    }

    fun get(id: String, vararg args: Any): String {
        var str = map[id] ?: id
        args.forEachIndexed { i, arg ->
            str = str.replace("%${i + 1}\$s", arg.toString()).replace("%s", arg.toString())
        }
        return str
    }
